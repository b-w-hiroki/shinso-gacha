const assert=require('node:assert/strict');
const model=require('../assets/personnel-discrepancies-model.js');
assert.deepEqual(model.CASES.map(c=>c.minRank),[3,6,10,14,17]);
assert.equal(model.current(0),null);
assert.equal(model.current(2),null);
assert.equal(model.current(3).id,'extra-seat');
assert.equal(model.current(6).id,'return-log');
assert.equal(model.current(10).id,'attendance');
assert.equal(model.current(14).id,'missing-predecessor');
assert.equal(model.current(17).id,'observer');
let state=model.normalize(null);
assert.deepEqual(model.unlocked(state,2),[]);
assert.equal(model.record(state,2,'records').fresh,false);
assert.equal(model.record(state,3,'__proto__').fresh,false);
const first=model.record(state,3,'records');assert(first.fresh);state=first.state;
assert.equal(model.record(state,3,'records').fresh,false);
assert.deepEqual(model.detail(state,3,'extra-seat').statements.map(s=>s.id),['records']);
assert.equal(model.confirm(state,3,'extra-seat').changed,false);
assert.equal(model.detail(state,2,'extra-seat'),null);
for(const id of ['equipment','senior'])state=model.record(state,3,id).state;
assert.equal(model.detail(state,3,'extra-seat').complete,true);
const comparison=model.confirm(state,3,'extra-seat');assert(comparison.changed);state=comparison.state;
assert.equal(model.confirm(state,3,'extra-seat').changed,false);
assert.equal(model.detail(state,3,'extra-seat').confirmed,true);
assert.equal(model.record(state,6,'records').caseId,'return-log');
assert.equal(model.detail(state,6,'extra-seat').confirmed,true);
assert.equal(model.detail(state,6,'return-log'),null);
const injected=model.normalize({statements:{'extra-seat':{records:true,senior:false,__proto__:true},'observer':{records:true}},confirmed:{'extra-seat':true,'observer':true}});
assert(!injected.confirmed['extra-seat']&&!injected.confirmed.observer);
assert.equal(model.detail(injected,3,'observer'),null,'high-tier evidence stays hidden');
const restored=model.normalize(JSON.parse(JSON.stringify(state)));
assert.deepEqual(restored,state,'saved evidence round trips');
console.log('Personnel contradiction model: 20 ranks, eligibility, partial testimony, idempotence, hidden records and save migration passed');
