const assert=require('node:assert/strict'),L=require('../assets/observation-location-model');
const modes=['cctv','photo','vision','dash'];
for(const mode of modes){
 assert.equal(L.current(mode,0,0),null);
 assert.equal(L.current(mode,1,1)?.mode,mode,'odd-sequence anomalies stay in the same place');
 assert.equal(L.current(mode,0,1)?.mode,mode);
 assert.equal(L.current(mode,0,3)?.mode,mode);
}
assert.equal(L.current('__proto__',0,1),null);
assert.equal(L.current('cctv',0,-1),null);
assert.equal(L.current('cctv',0,1.5),null);
const state={collection:{'photo:0':3},currency:700,sequence:4};
assert.equal(L.observe(state,{mode:'photo',rarity:1,sequence:1,readyAt:1000}),true,'acquired anomaly also identifies a real place');
assert.equal(L.observe(state,{mode:'photo',rarity:0,sequence:1,readyAt:1000}),false,'same observation sequence cannot be recounted');
assert.equal(L.observe(state,{mode:'photo',rarity:0,sequence:1,readyAt:1000}),false,'no repeated collection');
assert.equal(L.observe(state,{mode:'photo',rarity:0,sequence:3,readyAt:2000}),true);
assert.deepEqual(state.locationRecords['alt:photo'],{visits:2,lastSequence:3,firstAt:1000,rarities:{0:1,1:1}});
assert.equal(state.currency,700);assert.equal(state.sequence,4);assert.equal(state.collection['photo:0'],3);
assert.deepEqual(L.discovered({}),[]);
assert.equal(L.discovered(state.locationRecords).length,1);
assert.equal(L.byId('alt:photo').title,'夜の教室');
assert.equal(L.byId('alt:dash').title,'海沿いの夜道');
assert.equal(L.byId('alt:foo'),null);
assert.deepEqual(L.normalize({'unknown':{visits:999},'alt:photo':{visits:2,lastSequence:3,firstAt:1000}}),{'alt:photo':{visits:2,lastSequence:3,firstAt:1000,rarities:{0:2}}},'old visits migrate as only normal recordings');
assert.equal(L.overlay('photo',2),'assets/observation/alt-overlays/photo-2.svg');
assert.equal(L.overlay('photo',0),null);

const Legends=require('../assets/legend-model.js');
const levels=Object.fromEntries(Legends.ids.map(id=>[id,3]));
const knownSites=Object.fromEntries(modes.map(mode=>['alt:'+mode,{visits:1,lastSequence:1,firstAt:1000,rarities:{0:1}}]));
assert.equal(L.caseEcho('u1',{},Legends.CASES,knownSites,true),null,'unowned case cannot disclose clues');
assert.equal(L.caseEcho('u1',levels,Legends.CASES,{},true),null,'unvisited site stays hidden');
assert.equal(L.caseEcho('u1',levels,Legends.CASES,knownSites,false),null,'discovery needs a confirmed manual comparison');
assert.equal(L.caseEcho('__proto__',levels,Legends.CASES,knownSites,true),null);
assert.equal(L.caseEcho('u13',levels,Legends.CASES,knownSites,true),null);
const allEchoes=Legends.ids.map(id=>L.caseEcho(id,levels,Legends.CASES,knownSites,true));
assert.equal(allEchoes.filter(Boolean).length,12,'twelve owned cases match one of four actually visited sites');
assert.equal(new Set(allEchoes.map(x=>x.record)).size,12,'all twelve clues are authored separately');
assert.equal(allEchoes.filter(x=>x.after!==null).length,0,'normal source cannot fabricate an anomaly');
assert.equal(L.siteEchoes('alt:cctv',levels,Legends.CASES,knownSites,{}).length,0,'unconfirmed cases remain hidden in place catalog');
const noticed=Object.fromEntries(Legends.ids.map(id=>[id,true]));
assert.equal(L.siteEchoes('alt:cctv',levels,Legends.CASES,knownSites,noticed).length,3);
assert.equal(L.siteEchoes('alt:photo',levels,Legends.CASES,knownSites,noticed).length,3);
assert.equal(L.siteEchoes('alt:vision',levels,Legends.CASES,knownSites,noticed).length,3);
assert.equal(L.siteEchoes('alt:dash',levels,Legends.CASES,knownSites,noticed).length,3);
assert.deepEqual(L.siteEchoes('alt:unvisited',levels,Legends.CASES,knownSites,noticed),[]);
const richer=structuredClone(knownSites);richer['alt:cctv'].rarities[2]=1;
assert.equal(L.caseEcho('u1',levels,Legends.CASES,richer,true).after!==null,true,'earned anomaly offers a second layer');
assert.equal(L.caseEcho('u3',levels,Legends.CASES,richer,true).after,null,'different sites cannot borrow an anomaly');
const snapshot=JSON.stringify({levels,knownSites});L.siteEchoes('alt:cctv',levels,Legends.CASES,richer,noticed);
assert.equal(JSON.stringify({levels,knownSites}),snapshot,'comparison reads cannot change progress or original records');
console.log('Location archive: acquired R/SR/SSR variants, no duplicate discovery, migrated visits, no reward or save corruption');