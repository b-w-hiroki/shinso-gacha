const assert=require('node:assert/strict'),M=require('../assets/forecast-followup-model.js');
const morning=new Date(2026,9,11,8,0).getTime(),evening=new Date(2026,9,11,23,50).getTime();
const tomorrow=new Date(2026,9,12,0,10).getTime(),later=new Date(2026,9,12,9,0).getTime();
let result=M.issue(null,'u2','dash',evening);
assert(result.changed);let state=result.state;
assert.equal(M.inspect(state,'u2').status,'pending');
assert.equal(M.issue(state,'u2','dash',later).changed,false,'cannot reset issue time');
assert.deepEqual(M.collect(state,{mode:'dash',rarity:3},evening+30000).matched,[],'same day is not next day');
assert.deepEqual(M.collect(state,{mode:'cctv',rarity:1},tomorrow).matched,[],'unrelated scene cannot fulfill');
assert.deepEqual(M.collect(state,{mode:'dash',rarity:0},morning).matched,[],'backdated record cannot fulfill');
assert.deepEqual(M.collect(state,{mode:'dash',rarity:0},tomorrow).matched,['u2'],'midnight crossing is sufficient');
state=M.collect(state,{mode:'dash',rarity:0},tomorrow).state;
assert.equal(M.inspect(state,'u2').status,'compared');
assert.equal(M.inspect(state,'u2').rarity,0);
assert(M.inspect(state,'u2').copy.includes('平常'));
assert.deepEqual(M.collect(state,{mode:'dash',rarity:3},later).matched,[],'matching only once');
assert.equal(M.inspect(state,'u2').rarity,0,'later anomalies must not overwrite the report');
const migrated=M.normalize(JSON.parse(JSON.stringify(state)));
assert.deepEqual(migrated,state,'saving and reloading preserve evidence');
assert.equal(M.issue(migrated,'u0','dash',morning).changed,false);
assert.equal(M.issue(migrated,'__proto__','dash',morning).changed,false);
assert.equal(M.issue(migrated,'u2','unknown',morning).changed,false);
assert.equal(M.issue(migrated,'u1','cctv',Infinity).changed,false);
assert.equal(M.inspect(state,'u1'),null,'unclaimed report remains hidden');
const other=M.issue(state,'u3','photo',evening);
assert(other.changed);state=other.state;
assert.deepEqual(M.collect(state,{mode:'photo',rarity:2},tomorrow).matched,['u3']);
assert(M.inspect(M.collect(state,{mode:'photo',rarity:2},tomorrow).state,'u3').copy.includes('断定'));
const tampered=M.normalize({entries:{u2:{mode:'dash',issuedAt:evening,observedAt:evening+1000,rarity:3},u3:{mode:'photo',issuedAt:evening,observedAt:tomorrow,rarity:999},u999:{mode:'dash',issuedAt:evening}}});
assert.equal(M.inspect(tampered,'u2').status,'pending','same-day persisted completion rejected');
assert.equal(M.inspect(tampered,'u3').status,'pending','invalid rarity rejected');
assert.equal(M.inspect(tampered,'u999'),null);
console.log('Future report: acquisition, midnight, unrelated records, idempotence, frozen history and save migration passed');
