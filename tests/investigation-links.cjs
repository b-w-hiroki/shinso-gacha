const assert=require('node:assert/strict'),M=require('../assets/investigation-links-model'),Legend=require('../assets/legend-model');
const levels={u1:3,u2:3,u8:3,u3:0},cases=Legend.CASES;
const s=M.normalize({},levels,cases);
assert(M.links('u1',levels,cases).includes('u2'));
assert.deepEqual(M.links('u3',levels,cases),[]);
assert.equal(M.reappraise(s,'u1',levels,cases,false),false);
assert.equal(M.reappraise(s,'u1',levels,cases,true),true);
assert.equal(M.reappraise(s,'u1',levels,cases,true),false);
assert.equal(M.combine(s,'u1','u3',levels,cases),false);
assert.equal(M.combine(s,'u1','u2',levels,cases),true);
assert.equal(M.combine(s,'u2','u1',levels,cases),false);
const report=M.report('u1',levels,cases,{u1:0},s,{compared:true,linked:false});
assert.equal(report.hypothesis,0);assert.deepEqual(report.related,['u2']);assert.equal(report.reappraised,true);
const restored=M.normalize(JSON.parse(JSON.stringify(s)),levels,cases);
assert.deepEqual(restored,s);
assert.equal(M.report('u3',levels,cases,{},s,{}),null);
assert.deepEqual(M.normalize(restored,{u1:0,u2:3},cases).joint,{});
const h=M.normalize({},levels,cases,{u1:0});
assert.equal(M.revise(h,'u1',1,'compared',levels,cases,{u1:0},{compared:false}),false,'new evidence required');
assert.equal(M.revise(h,'u3',1,'compared',levels,cases,{u3:0},{compared:true}),false,'unowned case blocked');
assert.equal(M.revise(h,'u1',1,'compared',levels,cases,{u1:0},{compared:true}),true);
assert.equal(M.revise(h,'u1',0,'compared',levels,cases,{u1:0},{compared:true}),false,'stage cannot grant duplicate revision');
assert.equal(M.report('u1',levels,cases,{u1:0},h,{compared:true}).hypothesis,1);
assert.equal(M.report('u1',levels,cases,{u1:0},h,{compared:true}).initialHypothesis,0,'original remains immutable');
assert.equal(M.revise(h,'u1',0,'linked',levels,cases,{u1:0},{compared:true,linked:false}),false);
assert.equal(M.revise(h,'u1',0,'linked',levels,cases,{u1:0},{compared:true,linked:true}),true);
assert.equal(M.revise(h,'u1',1,'linked',levels,cases,{u1:0},{compared:true,linked:true}),false);
assert.deepEqual(M.normalize(JSON.parse(JSON.stringify(h)),levels,cases,{u1:0}).revisions.u1,[{basis:'compared',choice:1},{basis:'linked',choice:0}]);
assert.deepEqual(M.normalize(JSON.parse(JSON.stringify(h)),{u1:0},cases,{u1:0}).revisions,{},'unowned report history removed');
assert.deepEqual(M.normalize({revisions:{u1:[{basis:'compared',choice:1},{basis:'compared',choice:0},{basis:'linked',choice:3}]}},levels,cases,{u1:0}).revisions.u1,[{basis:'compared',choice:1}],'malformed history removed');
console.log('Evidence-gated hypothesis revision: originals, persistence, secrecy, idempotence passed');
console.log('Owned-only case links, reappraisal, idempotence and legacy save passed');