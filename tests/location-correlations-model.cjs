const assert=require('node:assert/strict');
const M=require('../assets/location-correlations-model');
const one={id:'alt:cctv',title:'地下通路',source:'CAM 12',file:'cctv-underground-upgraded.webp',visits:1,rarities:{0:1}};
const two={id:'alt:photo',title:'夜の教室',source:'PHOTO 18',file:'photo-classroom-upgraded.webp',visits:1,rarities:{0:1}};
const other={id:'alt:vision',title:'踏切前',source:'LINK 15',file:'vision-crossing-upgraded.webp',visits:1,rarities:{1:1}};
const fourth={id:'alt:dash',title:'海沿いの夜道',source:'DRIVE 19',file:'dash-coast-road-upgraded.webp',visits:1,rarities:{2:1}};
assert.deepEqual(M.list(null),[]);
assert.deepEqual(M.list([one]),[]);
assert.equal(M.inspect([one],'cctv-photo'),null,'both site records required');
assert.equal(M.inspect([one,two],'cctv-vision'),null,'unseen second site cannot appear');
const first=M.inspect([one,two],'cctv-photo');
assert(first&&first.record.length>20&&first.afterword);
assert.equal(first.rarity,null);
assert(first.afterword.includes('平常'));
assert.equal(M.list([one,two]).length,1);
assert.equal(M.list([one,two],'alt:cctv').length,1);
assert.equal(M.list([one,two],'alt:vision').length,0);
assert.deepEqual(M.list([one,two],'__proto__'),[]);
assert.equal(M.inspect([one,two],'not-real'),null);
const upgraded=M.inspect([{...one,rarities:{2:1}},{...two,rarities:{2:1}}],'cctv-photo');
assert.equal(upgraded.rarity,2);assert(upgraded.afterword.includes('異変'));
const all=M.list([one,two,other,fourth]);
assert.equal(all.length,6);
assert.equal(new Set(all.map(x=>x.id)).size,6);
assert.equal(new Set(all.map(x=>x.record)).size,6);
assert.deepEqual(M.list(JSON.parse(JSON.stringify([one,two]))),M.list([one,two]),'save round-trip');
assert.equal(M.list([one,{...two,visits:0}]).length,0,'unearned zero-visit item rejected');
assert.equal(M.list([one,{...two,id:'alt:bad'}]).length,0,'unknown site rejected');
assert.equal(M.list([one,two]).length,1,'no mutation during rereading');
console.log('Cross-site archive: earned-only links, pair IDs, individual copy, rare clues and save stability passed');
