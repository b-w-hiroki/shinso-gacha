const assert=require('node:assert/strict'),M=require('../assets/research-reports-model.js');
const levels={u1:3,u2:3,u3:2};let state=M.normalize(undefined,levels);
assert.equal(M.inspect(state,levels,'u3'),null);assert.equal(M.save(state,levels,'u3',0,'x',100).changed,false);
assert.equal(M.save(state,levels,'__proto__',1,'x',100).changed,false);
assert.equal(M.save(state,levels,'u1',4,'x',100).changed,false);
let x=M.save(state,levels,'u1',2,'まだ判断できない',100);assert(x.changed);state=x.state;
assert.deepEqual(M.inspect(state,levels,'u1').latest,{choice:2,note:'まだ判断できない',at:100});
assert.equal(M.save(state,levels,'u1',2,'まだ判断できない',150).changed,false);
state=M.save(state,levels,'u1',0,'この記録は改ざんされている',200).state;
state=M.save(state,levels,'u1',1,'別の可能性',300).state;
assert.equal(M.inspect(state,levels,'u1').revisions,3);
assert.deepEqual(M.inspect(state,levels,'u1').history.map(x=>x.choice),[1,0,2]);
assert.equal(M.inspect(state,levels,'u2').revisions,0);
const malicious='<script>alert(1)</script>';state=M.save(state,levels,'u1',2,malicious,400).state;
assert.equal(M.inspect(state,levels,'u1').latest.note,malicious,'source stays raw; UI must escape');
const before=JSON.stringify(state);
assert.deepEqual(M.normalize(JSON.parse(before),levels),state);
assert.equal(JSON.stringify(state),before,'model reads do not mutate caller');
assert.equal(M.normalize(state,{u1:0,u2:3}).files.u1,undefined,'unowned source remains hidden');
for(let i=0;i<35;i++)state=M.save(state,levels,'u1',i%3,'memo '+i,500+i).state;
assert.equal(M.inspect(state,levels,'u1').revisions,20,'history bounded without touching originals');
assert.equal(M.clean('a'.repeat(500)).length,280);
assert.equal(M.clean('\u0000bad'), 'bad');
